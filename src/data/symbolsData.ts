export function getSymbolsByCategory(cat: SymbolCategory): SpecialSymbol[] {
  if (cat === 'tutti') return SPECIAL_SYMBOLS;
  if (cat === 'popolari') return SPECIAL_SYMBOLS.filter((s) => s.isPopular);
  return SPECIAL_SYMBOLS.filter((s) => s.category === cat);
}

export function searchSymbols(query: string): SpecialSymbol[] {
  if (!query.trim()) return SPECIAL_SYMBOLS;
  const q = query.toLowerCase().trim();
  return SPECIAL_SYMBOLS.filter(
    (s) =>
      s.char.toLowerCase().includes(q) ||
      s.name.toLowerCase().includes(q) ||
      s.tags.some((t) => t.toLowerCase().includes(q))
  );
}
